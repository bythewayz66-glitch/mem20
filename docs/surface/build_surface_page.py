def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the page is stale")
    args = parser.parse_args()

    surface, catalog = load()
    problems = verify(surface, catalog)
    if problems:
        for problem in problems:
            print(f"::error::{problem}", file=sys.stderr)
        return 1

    rendered = build(surface, catalog)
    if args.check:
        if not OUT.is_file():
            print(f"::error::{OUT} is missing; run without --check", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != rendered:
            print(f"::error::{OUT} is stale; regenerate it", file=sys.stderr)
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} matches the surface pin")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(
        f"wrote {OUT.relative_to(ROOT)} — {len(rendered):,} bytes, "
        f"{surface['tools']} tools / {surface['domains']} domains"
    )
    return 0


