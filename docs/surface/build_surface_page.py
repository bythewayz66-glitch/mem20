#!/usr/bin/env python3
"""Build docs/surface/index.html — the 4.0 tool-surface page.

The page is generated, never hand-edited. It renders the *live* surface pin
from ``docs/surface.json`` (487 tools / 129 domains at v4.0.0) together with
the per-tool catalog in ``web/src/data/tools.json``, so the page cannot state a
number the repository does not already measure.

Inputs (both committed, both generated by other scripts):

  docs/surface.json          live ``tools/list`` + AST cross-check
                             (scripts/surface_manifest.py --write)
  web/src/data/tools.json    per-tool catalog: name, title, description,
                             domain, module, parameters

Output:

  docs/surface/index.html    static HTML. Every one of the 487 tools is in the
                             markup, so the page is complete without JS; the
                             inline script only filters what is already there.

Usage:

    python3 docs/surface/build_surface_page.py            # write
    python3 docs/surface/build_surface_page.py --check    # fail on drift
"""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SURFACE = ROOT / "docs" / "surface.json"
CATALOG = ROOT / "web" / "src" / "data" / "tools.json"
OUT = ROOT / "docs" / "surface" / "index.html"

# The commit the rendered data was derived from. Recorded on the page so a
# reader can diff the claim against the tree it came from.
DATA_COMMIT = "0224a64946a2c00313a9872515893157adcbc47e"


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def load() -> tuple[dict, dict]:
    surface = json.loads(SURFACE.read_text(encoding="utf-8"))
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    return surface, catalog


def verify(surface: dict, catalog: dict) -> list[str]:
    """Refuse to build a page whose numbers do not agree with each other."""
    problems: list[str] = []
    tools = int(surface["tools"])
    domains = int(surface["domains"])
    detail = surface["domains_detail"]

    if len(detail) != domains:
        problems.append(f"domains_detail has {len(detail)} rows, pin says {domains}")
    if sum(int(d["tools"]) for d in detail) != tools:
        problems.append("domains_detail tool counts do not sum to the pin")
    if sum(int(v) for v in surface["domain_counts"].values()) != tools:
        problems.append("domain_counts does not sum to the pin")
    if len(catalog["tools"]) != tools:
        problems.append(f"catalog has {len(catalog['tools'])} tools, pin says {tools}")
    if int(catalog["count"]) != tools or int(catalog["domain_count"]) != domains:
        problems.append("catalog count/domain_count disagree with the pin")
    cross = surface["cross_check"]
    if cross.get("only_ast") or cross.get("only_live"):
        problems.append("cross_check is not empty: the two collections disagree")
    if int(cross.get("ast_tools", -1)) != tools or int(cross.get("ast_domains", -1)) != domains:
        problems.append("cross_check ast_tools/ast_domains disagree with the pin")
    return problems


def build(surface: dict, catalog: dict) -> str:
    tools = int(surface["tools"])
    domains = int(surface["domains"])
    unwired = list(surface["unwired_tools"])
    detail = sorted(surface["domains_detail"], key=lambda d: (-int(d["tools"]), d["domain"]))
    by_domain: dict[str, list[dict]] = {}
    for tool in catalog["tools"]:
        by_domain.setdefault(tool["x"], []).append(tool)
    for rows in by_domain.values():
        rows.sort(key=lambda t: t["n"])

    # ---- domain cards -----------------------------------------------------
    cards: list[str] = []
    for index, dom in enumerate(detail, start=1):
        name = dom["domain"]
        rows = by_domain.get(name, [])
        prefixes = ", ".join(dom.get("prefixes") or []) or "—"
        modules = dom.get("modules") or []
        module_html = "".join(
            f'<code class="mod">{esc(m)}</code>' for m in modules
        ) or '<span class="muted">—</span>'
        tool_rows = []
        for tool in rows:
            params = tool.get("p") or []
            param_html = (
                '<span class="params">'
                + "".join(f'<span class="p">{esc(p)}</span>' for p in params)
                + "</span>"
                if params
                else '<span class="params"><span class="p none">no parameters</span></span>'
            )
            tool_rows.append(
                '<li class="tool" data-name="{n}" data-title="{t}" data-desc="{d}" data-domain="{x}">'
                '<div class="tool-head"><code class="tname">{n}</code>'
                '<span class="ttitle">{t}</span></div>'
                '<p class="tdesc">{d}</p>{params}</li>'.format(
                    n=esc(tool["n"]),
                    t=esc(tool.get("t") or tool["n"]),
                    d=esc(tool.get("d") or ""),
                    x=esc(name),
                    params=param_html,
                )
            )
        cards.append(
            '<article class="dom" id="d-{slug}" data-domain="{name}" data-count="{count}">'
            '<header class="dom-head">'
            '<div class="dom-id"><span class="dom-n">{index:03d}</span>'
            '<h3>{name}</h3></div>'
            '<span class="dom-count">{count}<span class="u">tools</span></span>'
            "</header>"
            '<div class="dom-meta"><span class="k">prefixes</span><span class="v mono">{prefixes}</span></div>'
            '<div class="dom-meta"><span class="k">modules</span><span class="v">{modules}</span></div>'
            '<ul class="tools">{rows}</ul>'
            "</article>".format(
                slug=esc(name),
                name=esc(name),
                index=index,
                count=len(rows),
                prefixes=esc(prefixes),
                modules=module_html,
                rows="".join(tool_rows),
            )
        )

    # ---- distribution bars ------------------------------------------------
    top = detail[:14]
    peak = max(int(d["tools"]) for d in top) if top else 1
    bars = "".join(
        '<li class="bar-row"><a class="bar-label" href="#d-{slug}">{name}</a>'
        '<span class="bar-track"><span class="bar-fill" style="width:{pct:.1f}%"></span></span>'
        '<span class="bar-val">{count}</span></li>'.format(
            slug=esc(d["domain"]),
            name=esc(d["domain"]),
            pct=(int(d["tools"]) / peak) * 100,
            count=int(d["tools"]),
        )
        for d in top
    )
    rest = domains - len(top)
    rest_tools = tools - sum(int(d["tools"]) for d in top)

    # ---- unwired ----------------------------------------------------------
    unwired_items = "".join(
        f'<li><code>{esc(name)}</code></li>' for name in unwired
    )

    # ---- domain chips -----------------------------------------------------
    chips = "".join(
        '<button class="chip" type="button" data-filter="{name}">{name}'
        '<span class="chip-n">{count}</span></button>'.format(
            name=esc(d["domain"]), count=int(d["tools"])
        )
        for d in detail
    )

    return TEMPLATE.format(
        tools=tools,
        domains=domains,
        unwired_count=len(unwired),
        data_commit=DATA_COMMIT,
        cards="".join(cards),
        bars=bars,
        rest=rest,
        rest_tools=rest_tools,
        unwired_items=unwired_items,
        chips=chips,
        top_domain=esc(detail[0]["domain"]) if detail else "—",
        top_domain_tools=int(detail[0]["tools"]) if detail else 0,
        catalog_source=esc(catalog.get("source", "")),
        surface_source=esc(surface.get("source", "")),
    )


