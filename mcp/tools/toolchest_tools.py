"""Toolchest tools for the mem20 MCP server.

Exposes the tool inventory registry to agents: what tools exist on this box,
what each one is, and whether the registry's own cross-subsystem wiring is
live. The registry is generated by ``toolchest`` from real on-box discovery
(MCP server table, PATH binaries, native subsystems) -- these tools read that
inventory, they never invent entries.

Two tools:

* ``toolchest_inventory`` -- query the registry (list / search / show / stats)
* ``toolchest_wiring``    -- prove the registry's cross-subsystem edges

Both are thin: the work lives in the ``toolchest`` package so the CLI and the
MCP surface can never disagree about what the registry says.
"""
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict

try:
    from mcp.server import Server
    from mcp.server.lowlevel.server import ServerRequestContext
    import mcp_types as mt
    MCP_SDK_AVAILABLE = True
    MCP_SDK_IMPORT_ERROR = None
except ImportError as _mcp_sdk_exc:  # pragma: no cover - only without the SDK
    # Never sys.exit() at import time: pytest imports this module during
    # collection and a SystemExit aborts the whole session instead of
    # reporting one collection error. Full note in mcp/server.py.
    MCP_SDK_AVAILABLE = False
    MCP_SDK_IMPORT_ERROR = _mcp_sdk_exc


def _toolchest():
    """Import the toolchest package from the estate, wherever it lives."""
    try:
        import toolchest  # noqa: F401
        from toolchest import catalog, integrations
        return catalog, integrations
    except ImportError:
        pass
    root = Path(os.environ.get("MEM20_ROOT", "/opt/mem20"))
    for candidate in (root / "toolchest" / "src", root / "toolchest"):
        if (candidate / "toolchest" / "__init__.py").is_file():
            sys.path.insert(0, str(candidate))
            break
    from toolchest import catalog, integrations
    return catalog, integrations


def _inventory_path() -> Path:
    root = Path(os.environ.get("MEM20_ROOT", "/opt/mem20"))
    return root / "toolchest" / "inventory.json"


class ToolchestToolsMixin:
    """Tool inventory registry tools for mem20."""

    def register_toolchest_tools(self):
        """Register the toolchest registry tools."""
        if not MCP_SDK_AVAILABLE:  # pragma: no cover
            return
        self.tools["toolchest_inventory"] = mt.Tool(
            name="toolchest_inventory",
            title="Toolchest Inventory",
            description=(
                "Query the mem20 tool registry: every MCP tool, every CLI binary on "
                "PATH, and every native mem20 subsystem, with real runtime status. "
                "action=list filters by kind/category; action=search matches names and "
                "descriptions; action=show returns one entry; action=stats returns counts."
            ),
            inputSchema={
                "type": "object",
                "properties": {
                    "action": {
                        "type": "string",
                        "enum": ["list", "search", "show", "stats"],
                        "default": "stats",
                    },
                    "term": {"type": "string", "description": "search term (action=search)"},
                    "name": {"type": "string", "description": "entry name or id (action=show)"},
                    "kind": {"type": "string", "enum": ["mcp", "cli", "subsystem"]},
                    "category": {"type": "string"},
                    "limit": {"type": "integer", "default": 25},
                },
                "required": [],
            },
        )
        self.tools["toolchest_wiring"] = mt.Tool(
            name="toolchest_wiring",
            title="Toolchest Wiring",
            description=(
                "Prove the tool registry's cross-subsystem edges by calling each one: "
                "memory_engine pin_block, mem20kanbanz sha256, mem20ops declared_scripts, "
                "mem20corez CharMLP, mem20cliz build_envelope, mem20verify discover_packages. "
                "Returns per-edge ok/result so a broken edge is visible, not assumed."
            ),
            inputSchema={
                "type": "object",
                "properties": {
                    "root": {"type": "string", "description": "estate root override"},
                },
                "required": [],
            },
        )

    async def _toolchest_inventory(self, arguments: Dict[str, Any]) -> str:
        catalog, _integrations = _toolchest()
        action = (arguments.get("action") or "stats").lower()
        path = _inventory_path()
        if not path.is_file():
            return json.dumps({
                "ok": False,
                "error": f"inventory not found at {path}",
                "hint": "run `python -m toolchest refresh` on the box",
            })
        inv = catalog.load_inventory(path)

        if action == "stats":
            return json.dumps({
                "ok": True,
                "generated_at": inv.get("generated_at"),
                "counts": inv.get("counts", {}),
                "categories": inv.get("categories", {}),
                "notes": inv.get("notes", []),
            }, indent=2)

        entries = inv.get("entries", [])
        if action == "show":
            target = (arguments.get("name") or "").lower()
            for entry in entries:
                if entry["name"].lower() == target or entry["id"].lower() == target:
                    return json.dumps({"ok": True, "entry": entry}, indent=2)
            return json.dumps({"ok": False, "error": f"no entry named {target!r}"})

        if action == "search":
            term = (arguments.get("term") or "").lower()
            if not term:
                return json.dumps({"ok": False, "error": "action=search needs a term"})
            hits = [e for e in entries
                    if term in " ".join([e["name"], e.get("description", ""),
                                         e.get("category", ""),
                                         e.get("subcategory", "")]).lower()]
        else:
            hits = entries
            kind = (arguments.get("kind") or "").lower()
            category = (arguments.get("category") or "").lower()
            if kind:
                hits = [e for e in hits if e["kind"].lower() == kind]
            if category:
                hits = [e for e in hits
                        if e["category"].lower() == category
                        or e.get("subcategory", "").lower() == category]

        limit = int(arguments.get("limit") or 25)
        return json.dumps({
            "ok": True,
            "matched": len(hits),
            "returned": min(limit, len(hits)),
            "entries": [
                {"id": e["id"], "kind": e["kind"], "name": e["name"],
                 "category": e["category"], "subcategory": e.get("subcategory", ""),
                 "runtime_status": e.get("runtime_status", ""),
                 "description": (e.get("description") or "")[:200]}
                for e in hits[:limit]
            ],
        }, indent=2)

    async def _toolchest_wiring(self, arguments: Dict[str, Any]) -> str:
        _catalog, integrations = _toolchest()
        root = arguments.get("root")
        report = integrations.wiring_report(Path(root) if root else None)
        return json.dumps(report, indent=2, default=str)
