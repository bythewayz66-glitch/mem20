"""mem20 autonomous / auto systems runtime.

Consolidates every organ whose package name contained ``auto`` (except this
package) into one product surface. Implementations are vendored under
``members/<former-package>/``.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

__version__ = "0.2.0"

MEMBERS = (
    "mem20autonomouscodesurgeonz",
    "mem20autonomousdealdeskz",
    "mem20autonomousmicrosaasfoundryz",
    "mem20autonomousrecoverydirectorz",
    "mem20autonomousreviewswarmz",
    "mem20autonomoussaleslaboratoryz",
    "mem20autonomoussoftwarefoundryz",
    "mem20autonomoustrafficcontrollerz",
    "mem20autonomousworkcellsz",
    "mem20autogeneratedprototypepathz",
    "mem20autouez",
    "mem20databaseautopilotz",
    "mem20deviceenrollmentautopilotz",
    "mem20personalautomationcanvasz",
    "mem20protocolautodiscoveryenginez",
    "mem20realtimeeventautopilotz",
    "mem20uniteconomicsautopilotz",
    "mem20dailydecisioncopilotz",
    "mem20smartmeetingcopilotz",
)

_MEMBERS_ROOT = Path(__file__).resolve().parent.parent / "members"


def member_path(name: str) -> Path:
    return _MEMBERS_ROOT / name


def load_member(name: str):
    """Load a vendored auto member by former package name."""
    if name not in MEMBERS:
        raise KeyError(f"unknown auto member {name!r}")
    base = member_path(name)
    candidates = [
        base / name / "__init__.py",
        base / "src" / name / "__init__.py",
        base / name / "runtime.py",
        base / name / "core.py",
    ]
    for init in candidates:
        if not init.is_file():
            continue
        if init.name != "__init__.py":
            spec = importlib.util.spec_from_file_location(f"mem20autoz.members.{name}", init)
            mod = importlib.util.module_from_spec(spec)
            assert spec.loader is not None
            sys.modules[spec.name] = mod
            spec.loader.exec_module(mod)
            return mod
        if str(init.parent.parent) not in sys.path:
            sys.path.insert(0, str(init.parent.parent))
        return __import__(name)
    raise FileNotFoundError(f"no vendored sources for {name} under {base}")


__all__ = ["__version__", "MEMBERS", "member_path", "load_member"]
