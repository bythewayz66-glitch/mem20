def families() -> List[str]:
    """Every family, sorted."""
    return sorted(FAMILIES)


def purpose(family: str) -> str:
    """What a family is for. Empty string when unknown."""
    return FAMILIES.get(family, "")


def members(family: str) -> List[str]:
    """Packages in a family, sorted."""
    return sorted(p for p, f in ASSIGNMENT.items() if f == family)


def family_of(package: str) -> Optional[str]:
    """The family a package belongs to, or None if it is not registered."""
    return ASSIGNMENT.get(package)


def spec(package: str) -> Optional[dict]:
    """Full spec for one package. None when it is not registered."""
    fam = ASSIGNMENT.get(package)
    if fam is None:
        return None
    return {
        "package": package,
        "family": fam,
        "name": NAMES.get(package, package),
        "purpose": FAMILIES.get(fam, ""),
        "must_refuse": ("a generic runtime body, and a confident answer "
                       "when out of its depth"),
        "proven_by": ("a test asserting a specific value, bound or "
                     "contradiction - never that the function ran"),
    }


def orphans() -> List[str]:
    """Families with no members. Empty means every family has work in it."""
    return sorted(f for f in FAMILIES if not members(f))


def unmapped() -> List[str]:
    """Registered packages with no family. Should always be empty."""
    return sorted(p for p in NAMES if p not in ASSIGNMENT)


def stats() -> dict:
    """Integrity check that can be asserted in a test."""
    counts = {f: len(members(f)) for f in FAMILIES}
    return {
        "families": len(FAMILIES),
        "packages": len(ASSIGNMENT),
        "named": len(NAMES),
        "orphan_families": len(orphans()),
        "unmapped": len(unmapped()),
        "largest": max(counts.values()) if counts else 0,
        "smallest": min(counts.values()) if counts else 0,
    }


