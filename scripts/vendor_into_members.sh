#!/usr/bin/env bash
# Vendor absorbed organ sources into mem20adapz/members and mem20autoz/members
# BEFORE running DELETE_ORIGINALS.sh. Run from repo root on chore/merge-adapz-autoz.
set -euo pipefail

copy_tree() {
  local src="$1" dest="$2"
  if [ ! -d "$src" ]; then
    echo "skip missing $src"
    return 0
  fi
  mkdir -p "$dest"
  if command -v rsync >/dev/null 2>&1; then
    rsync -a --exclude '*.whl' --exclude '__pycache__' --exclude '.git' "$src"/ "$dest"/
  else
    cp -a "$src"/. "$dest"/
  fi
  echo "vendored $src -> $dest"
}

# adaptive -> mem20adapz
copy_tree mem20adaptiveachievementenginez mem20adapz/members/achievement
