#!/usr/bin/env perl
# Regenerate lib/Mem20/Surface.pm from the repository's authoritative surface
# manifest.
#
#   perl xt/gen-surface.pl            # rewrite lib/Mem20/Surface.pm
#   perl xt/gen-surface.pl --check    # exit 1 if the checked-in file is stale
#
# WHY THIS EXISTS
#
# The SDK used to carry only two integers (SURFACE_TOOL_COUNT and
# SURFACE_DOMAIN_COUNT). A count cannot tell a caller WHICH tool moved: when the
# server grew from 270 to 487 tools, `verify_surface` could only say "the number
# is different", and a rename that kept the count identical was invisible.
#
# The repository already publishes the full name list in two places that are
# cross-checked against each other by scripts/surface_manifest.py:
#
#   docs/surface.json          counts, domain names, per-domain detail
#   web/src/data/tools.json    one record per tool: name, domain, module, params
#
# This generator reads both, refuses to emit unless they agree, and writes a
# plain Perl module holding the names and the domain map. No JSON parsing at
# runtime, no non-core dependency, and the data is reviewable in a diff.
#
# The generated file is checked in. `--check` is what CI runs, so a surface
# change that is not accompanied by a regenerated module fails the build rather
# than silently shipping a stale manifest.

use strict;
use warnings;

use FindBin ();
use File::Spec ();

my $DIST = File::Spec->rel2abs( File::Spec->catdir( $FindBin::Bin, File::Spec->updir ) );
my $REPO = File::Spec->rel2abs( File::Spec->catdir( $DIST, File::Spec->updir, File::Spec->updir ) );

my $SURFACE_JSON = File::Spec->catfile( $REPO, 'docs', 'surface.json' );
my $TOOLS_JSON   = File::Spec->catfile( $REPO, 'web', 'src', 'data', 'tools.json' );
my $OUT          = File::Spec->catfile( $DIST, 'lib', 'Mem20', 'Surface.pm' );

my $CHECK = grep { $_ eq '--check' } @ARGV;

# ---------------------------------------------------------------- JSON reading
#
# JSON::PP is core, so the generator needs nothing installed either. It is a
# build-time tool, not a runtime dependency of the distribution.

require JSON::PP;

sub slurp_json {
    my ($path) = @_;
    open my $fh, '<:raw', $path or die "cannot read $path: $!\n";
    my $raw = do { local $/; <$fh> };
    close $fh;
    my $decoded = eval { JSON::PP->new->utf8->decode($raw) };
    die "cannot decode $path: $@\n" if $@;
    return $decoded;
}

for my $path ( $SURFACE_JSON, $TOOLS_JSON ) {
    die "missing surface source: $path\n" unless -f $path;
}

my $surface = slurp_json($SURFACE_JSON);
my $catalog = slurp_json($TOOLS_JSON);

# ------------------------------------------------------- cross-check the inputs
#
# The two files are generated by different code paths (a live tools/list round
# trip, and an AST scan of the tool modules). If they disagree, one of them is
# wrong and emitting either would bake the disagreement into the SDK.

my @catalog_tools = map { $_->{n} } @{ $catalog->{tools} || [] };

my %seen;
my @dupes = grep { $seen{$_}++ } @catalog_tools;
die "tools.json contains duplicate tool names: @dupes\n" if @dupes;

my @catalog_domains = sort keys %{ { map { $_->{x} => 1 } @{ $catalog->{tools} || [] } } };
my @surface_domains = sort @{ $surface->{domain_names} || [] };

die sprintf(
    "domain sets disagree: tools.json has %d, surface.json has %d\n",
    scalar @catalog_domains, scalar @surface_domains
) unless "@catalog_domains" eq "@surface_domains";

my $n_tools   = scalar @catalog_tools;
my $n_domains = scalar @catalog_domains;

die "tools.json count ($n_tools) disagrees with its own count field ($catalog->{count})\n"
    if defined $catalog->{count} && $catalog->{count} != $n_tools;

die "surface.json tools ($surface->{tools}) disagrees with tools.json ($n_tools)\n"
    if defined $surface->{tools} && $surface->{tools} != $n_tools;

die "surface.json domains ($surface->{domains}) disagrees with tools.json ($n_domains)\n"
    if defined $surface->{domains} && $surface->{domains} != $n_domains;

# The AST cross-check block is the generator's own assertion that the live
# tools/list and the source scan agree. Refuse to emit if it reports a delta.
my $cross = $surface->{cross_check} || {};
for my $key (qw(only_ast only_live)) {
    my $list = $cross->{$key};
    next unless ref $list eq 'ARRAY' && @$list;
    die "surface.json cross_check.$key is non-empty (@$list) -- the live surface "
      . "and the AST catalog disagree\n";
}

# ------------------------------------------------------------------- emit Perl
#
# Every heredoc below is single-quoted: the generated module is full of sigils
# and interpolating them here would either expand them against this script's
# variables or fail to compile. Placeholders are substituted explicitly.

my $names_block = '';
my $line = '';
for my $name (@catalog_tools) {
    if ( length($line) + length($name) + 1 > 76 ) {
        $names_block .= "    $line\n";
        $line = '';
    }
    $line .= ( length $line ? ' ' : '' ) . $name;
}
$names_block .= "    $line\n" if length $line;

my $domain_block = '';
for my $tool ( sort { $a->{n} cmp $b->{n} } @{ $catalog->{tools} } ) {
    $domain_block .= sprintf "    %-44s => '%s',\n", "'$tool->{n}'", $tool->{x};
}

my $body = <<'HEAD';
package Mem20::Surface;
use strict;
use warnings;

# GENERATED FILE -- DO NOT EDIT BY HAND.
#
# Regenerate with:  perl xt/gen-surface.pl
# Verify in CI:     perl xt/gen-surface.pl --check
#
# Source of truth:
#   docs/surface.json        (live tools/list, cross-checked against the AST)
#   web/src/data/tools.json  (one record per tool: name, domain, module)
#
# Both are produced by scripts/surface_manifest.py in the mem20 repository. The
# generator refuses to emit unless the two agree, so this module cannot encode
# a disagreement between the live server and the source tree.
#
# Why a generated module instead of a runtime JSON read: the SDK installs with
# nothing but core Perl and must not depend on a checkout being present. Baking
# the names in keeps that promise while still letting verify_surface() name the
# exact tools that moved, which a bare integer count cannot do.

our $VERSION = '0.3.0';

# The surface this SDK release was generated against.
our $TOOL_COUNT   = __TOOL_COUNT__;
our $DOMAIN_COUNT = __DOMAIN_COUNT__;

# Every tool name the server advertises, sorted. Sorted so a diff of this file
# shows additions and removals rather than reshuffling.
our @TOOL_NAMES = qw(
__NAMES__
);

# Tool name => owning domain, as declared by the tool's module in the AST
# catalog. This is the registration-time domain, not a prefix bucket: memory_*
# and vault_* are separate prefixes inside one domain, and a bare `reflexion`
# has no underscore at all.
our %TOOL_DOMAIN = (
__DOMAINS__
);

# Domain => the tools it owns, built from %TOOL_DOMAIN so the two can never
# disagree.
our %DOMAIN_TOOLS;
{
    my %by_domain;
    push @{ $by_domain{ $TOOL_DOMAIN{$_} } }, $_ for sort keys %TOOL_DOMAIN;
    %DOMAIN_TOOLS = %by_domain;
}

# The domain names, sorted.
our @DOMAIN_NAMES = sort keys %DOMAIN_TOOLS;

# True when the server advertises this tool.
sub has_tool {
    my ( $class, $name ) = @_;
    return 0 unless defined $name;
    return exists $TOOL_DOMAIN{$name} ? 1 : 0;
}

# The domain that owns a tool, or undef.
sub domain_of {
    my ( $class, $name ) = @_;
    return undef unless defined $name;
    return $TOOL_DOMAIN{$name};
}

# The tools owned by a domain, as a list. Empty when the domain is unknown.
sub tools_in {
    my ( $class, $domain ) = @_;
    return () unless defined $domain;
    return @{ $DOMAIN_TOOLS{$domain} || [] };
}

# Compare a live tool-name list against this manifest.
#
# Returns a hashref with the counts, the names the server advertises but this
# SDK does not know (extra), and the names this SDK expects but the server did
# not advertise (missing). Both lists are sorted, so a failure message is
# stable across runs.
sub diff {
    my ( $class, $live_names ) = @_;

    my %live  = map { $_ => 1 } @{ $live_names || [] };
    my %known = map { $_ => 1 } @TOOL_NAMES;

    my @missing = sort grep { !$live{$_} } @TOOL_NAMES;
    my @extra   = sort grep { !$known{$_} } keys %live;

    return {
        ok             => ( @missing || @extra ) ? 0 : 1,
        tools          => scalar keys %live,
        expected_tools => $TOOL_COUNT,
        domains        => $DOMAIN_COUNT,
        missing        => \@missing,
        extra          => \@extra,
    };
}

1;
__END__

=head1 NAME

Mem20::Surface - the mem20 tool surface this SDK was generated against

=head1 DESCRIPTION

B<Generated file.> Do not edit by hand; run C<perl xt/gen-surface.pl>.

Holds the full tool-name list (__TOOL_COUNT__ names) and the tool-to-domain map
(__DOMAIN_COUNT__ domains) that C<Mem20::Client/verify_surface> compares a live
C<tools/list> against. A count alone cannot say I<which> tool moved; this
module can.

The data comes from C<docs/surface.json> and C<web/src/data/tools.json> in the
mem20 repository, which C<scripts/surface_manifest.py> generates from a live
C<tools/list> round trip and cross-checks against an AST scan of the tool
modules. The generator refuses to emit unless the two agree.

=head1 CLASS METHODS

=over 4

=item C<< Mem20::Surface->has_tool($name) >> - is this tool advertised?

=item C<< Mem20::Surface->domain_of($name) >> - the owning domain, or undef.

=item C<< Mem20::Surface->tools_in($domain) >> - the tools a domain owns.

=item C<< Mem20::Surface->diff(\@live_names) >> - compare a live list against
this manifest. Returns C<ok>, C<tools>, C<expected_tools>, C<domains>,
C<missing> and C<extra>.

=back

=head1 VARIABLES

C<$TOOL_COUNT>, C<$DOMAIN_COUNT>, C<@TOOL_NAMES>, C<%TOOL_DOMAIN>,
C<%DOMAIN_TOOLS>, C<@DOMAIN_NAMES>.

=cut
HEAD

$body =~ s/__TOOL_COUNT__/$n_tools/g;
$body =~ s/__DOMAIN_COUNT__/$n_domains/g;
$body =~ s/__NAMES__/$names_block/;
$body =~ s/__DOMAINS__/$domain_block/;

# ------------------------------------------------------------------- write/check

if ($CHECK) {
    my $existing = '';
    if ( -f $OUT ) {
        open my $fh, '<:raw', $OUT or die "cannot read $OUT: $!\n";
        $existing = do { local $/; <$fh> };
        close $fh;
    }

    if ( $existing ne $body ) {
        print STDERR "lib/Mem20/Surface.pm is stale; run: perl xt/gen-surface.pl\n";
        exit 1;
    }
    print "lib/Mem20/Surface.pm is up to date ($n_tools tools, $n_domains domains)\n";
    exit 0;
}

open my $out, '>:raw', $OUT or die "cannot write $OUT: $!\n";
print {$out} $body;
close $out;

print "wrote lib/Mem20/Surface.pm: $n_tools tools, $n_domains domains\n";
