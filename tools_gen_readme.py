"""Generate factual READMEs for mem20 subsystems that lack one.

Every statement in the generated README is derived from files on disk:
pyproject metadata, real module files, real entry points, real test files.
No claim is written that is not read from the tree.
"""
import ast, json, os, re, sys
from pathlib import Path

ROOT = Path("/opt/mem20")
# Directories that are data, not subsystems.
SKIP = {"backups","data","entries","store","plans","notes","proof","incoming",
        "loaders","tests","test","verification","tools","bench","mem20.egg-info",
        "systemd","tool worlds"}


def scan(d: Path):
    info = {"py": 0, "loc": 0, "tests": 0, "entry_points": [], "deps": [],
            "name": d.name, "desc": "", "top_modules": []}
    pyproject = d / "pyproject.toml"
    if pyproject.exists():
        t = pyproject.read_text(errors="ignore")
        m = re.search(r'^\s*name\s*=\s*"([^"]+)"', t, re.M)
        if m: info["name"] = m.group(1)
        m = re.search(r'^\s*description\s*=\s*"([^"]+)"', t, re.M)
        if m: info["desc"] = m.group(1)
        sec = re.search(r"\[project\.scripts\](.*?)(\n\[|\Z)", t, re.S)
        if sec:
            info["entry_points"] = re.findall(r'^\s*([\w\-]+)\s*=\s*"([^"]+)"', sec.group(1), re.M)
        dep = re.search(r"dependencies\s*=\s*\[(.*?)\]", t, re.S)
        if dep:
            info["deps"] = [x.strip().strip('"\'') for x in dep.group(1).split(",")
                            if x.strip()][:12]
    for root, dirs, files in os.walk(d):
        dirs[:] = [x for x in dirs if x not in (".venv", "__pycache__", "node_modules", ".git", "tests", "test")]
        for f in files:
            if f.endswith(".py"):
                fp = Path(root) / f
                if f.startswith("test_"):
                    info["tests"] += 1
                    continue
                try:
                    src = fp.read_text(errors="ignore")
                except Exception:
                    continue
                info["py"] += 1
                info["loc"] += src.count("\n") + 1
    # tests dir separately
    for tdir in ("tests", "test"):
        tp = d / tdir
        if tp.exists():
            for root, dirs, files in os.walk(tp):
                dirs[:] = [x for x in dirs if x not in ("__pycache__",)]
                info["tests"] += sum(1 for f in files if f.startswith("test_") and f.endswith(".py"))
    top = [p.name for p in sorted(d.glob("*.py"))]
    info["top_modules"] = top[:10]
    return info


def render(d: Path, i: dict) -> str:
    L = [f"# {i['name']}", ""]
    if i["desc"]:
        L += [f"> {i['desc']}", ""]
    L += ["Generated by `tools_gen_readme.py` from the files on disk. "
          "Every figure below was measured, not estimated.", ""]
    L += ["## At a glance", "",
          "| metric | value |", "|---|---|",
          f"| python modules | {i['py']} |",
          f"| lines of python | {i['loc']:,} |",
          f"| test files | {i['tests']} |",
          f"| console entry points | {len(i['entry_points'])} |", ""]
    if i["entry_points"]:
        L += ["## Entry points", "", "| command | target |", "|---|---|"]
        for name, tgt in i["entry_points"][:15]:
            L.append(f"| `{name}` | `{tgt}` |")
        L.append("")
    if i["deps"]:
        L += ["## Declared dependencies", "", ", ".join(f"`{x.split('>')[0].split('=')[0].strip()}`" for x in i["deps"]) + "", ""]
    if i["top_modules"]:
        L += ["## Top-level modules", ""]
        L += [f"- `{m}`" for m in i["top_modules"]]
        L.append("")
    L += ["## Verification", "",
          "```bash",
          f"cd /opt/mem20/{d.name}",
          f"/root/.venv/bin/python -c \"import pathlib;print('modules:',len([p for p in pathlib.Path('.').rglob('*.py')]))\"",
          "```", ""]
    return "\n".join(L)


def main():
    targets = [d for d in sorted(ROOT.iterdir())
               if d.is_dir() and not d.name.startswith(".") and d.name not in SKIP
               and not any(f.upper().startswith("README")
                           for f in (os.listdir(d) if os.access(d, os.R_OK) else []))]
    made = []
    for d in targets:
        i = scan(d)
        if i["py"] == 0 and not i["entry_points"]:
            continue          # not a code subsystem
        (d / "README.md").write_text(render(d, i))
        made.append({"dir": d.name, "modules": i["py"], "loc": i["loc"],
                     "tests": i["tests"], "entry_points": len(i["entry_points"])})
    print(json.dumps({"readmes_written": len(made), "detail": made}, indent=1))

if __name__ == "__main__":
    main()
